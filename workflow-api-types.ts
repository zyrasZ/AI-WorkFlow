// API Service Class
// ============================================

export class WorkflowAPI {
  private baseUrl: string;

  constructor(baseUrl: string = 'http://localhost:3000') {
    this.baseUrl = baseUrl;
  }

  private getHeaders(): HeadersInit {
    const token = typeof window !== 'undefined' 
      ? localStorage.getItem('access_token') 
      : null;
    
    return {
      'Authorization': `Bearer ${token}`,
      'Content-Type': 'application/json'
    };
  }

  private async request<T>(
    endpoint: string,
    options?: RequestInit
  ): Promise<T> {
    const response = await fetch(`${this.baseUrl}${endpoint}`, {
      ...options,
      headers: {
        ...this.getHeaders(),
        ...options?.headers
      }
    });

    if (!response.ok) {
      const error = await response.json();
      throw new Error(error.error || error.message || 'API request failed');
    }

    const json = await response.json();
    return json.data || json;
  }

  // ============================================
  // Workflow Management
  // ============================================

  async listWorkflows(): Promise<Workflow[]> {
    return this.request<Workflow[]>('/api/workflows');
  }

  async getWorkflow(id: string): Promise<Workflow> {
    return this.request<Workflow>(`/api/workflows/${id}`);
  }

  async createWorkflow(data: {
    name: string;
    description?: string;
    nodes: WorkflowNode[];
    edges: WorkflowEdge[];
  }): Promise<Workflow> {
    return this.request<Workflow>('/api/workflows', {
      method: 'POST',
      body: JSON.stringify(data)
    });
  }

  async updateWorkflow(
    id: string,
    data: Partial<Workflow>
  ): Promise<Workflow> {
    return this.request<Workflow>(`/api/workflows/${id}`, {
      method: 'PATCH',
      body: JSON.stringify(data)
    });
  }

  async deleteWorkflow(id: string): Promise<void> {
    await this.request(`/api/workflows/${id}`, {
      method: 'DELETE'
    });
  }

  // ============================================
  // Workflow Execution
  // ============================================

  async executeWorkflow(
    id: string,
    input?: Record<string, any>
  ): Promise<{ executionId: string }> {
    return this.request(`/api/workflows/${id}/execute`, {
      method: 'POST',
      body: JSON.stringify({ input })
    });
  }

  async validateWorkflow(id: string): Promise<ValidationResult> {
    return this.request<ValidationResult>(`/api/workflows/${id}/validate`);
  }

  async getExecution(id: string): Promise<WorkflowExecution> {
    return this.request<WorkflowExecution>(`/api/executions/${id}`);
  }

  async listExecutions(params?: {
    workflow_id?: string;
    status?: ExecutionStatus;
    limit?: number;
    offset?: number;
  }): Promise<WorkflowExecution[]> {
    const query = new URLSearchParams(params as any).toString();
    return this.request<WorkflowExecution[]>(`/api/executions?${query}`);
  }

  // ============================================
  // Triggers
  // ============================================

  async listTriggers(workflowId: string): Promise<TriggerConfig[]> {
    return this.request<TriggerConfig[]>(
      `/api/workflows/${workflowId}/triggers`
    );
  }

  async createTrigger(
    workflowId: string,
    data: {
      trigger_type: TriggerType;
      config: any;
      is_active?: boolean;
    }
  ): Promise<TriggerConfig> {
    return this.request<TriggerConfig>(
      `/api/workflows/${workflowId}/triggers`,
      {
        method: 'POST',
        body: JSON.stringify(data)
      }
    );
  }

  async updateTrigger(
    workflowId: string,
    triggerId: string,
    data: Partial<TriggerConfig>
  ): Promise<TriggerConfig> {
    return this.request<TriggerConfig>(
      `/api/workflows/${workflowId}/triggers/${triggerId}`,
      {
        method: 'PATCH',
        body: JSON.stringify(data)
      }
    );
  }

  async deleteTrigger(workflowId: string, triggerId: string): Promise<void> {
    await this.request(`/api/workflows/${workflowId}/triggers/${triggerId}`, {
      method: 'DELETE'
    });
  }

  // ============================================
  // Node Types
  // ============================================

  async getNodeTypes(): Promise<NodeTypeDefinition[]> {
    return this.request<NodeTypeDefinition[]>('/api/node-types');
  }

  // ============================================
  // Email Accounts
  // ============================================

  async listEmailAccounts(): Promise<EmailAccount[]> {
    return this.request<EmailAccount[]>('/api/email/accounts');
  }

  async getEmailAccount(id: string): Promise<EmailAccount> {
    return this.request<EmailAccount>(`/api/email/accounts/${id}`);
  }

  async createEmailAccount(data: {
    name: string;
    email_address: string;
    provider: EmailProvider;
    auth_type: 'imap-smtp' | 'oauth2';
    config: EmailAccountConfig;
  }): Promise<EmailAccount> {
    return this.request<EmailAccount>('/api/email/accounts', {
      method: 'POST',
      body: JSON.stringify(data)
    });
  }

  async updateEmailAccount(
    id: string,
    data: Partial<EmailAccount>
  ): Promise<EmailAccount> {
    return this.request<EmailAccount>(`/api/email/accounts/${id}`, {
      method: 'PATCH',
      body: JSON.stringify(data)
    });
  }

  async deleteEmailAccount(id: string): Promise<void> {
    await this.request(`/api/email/accounts/${id}`, {
      method: 'DELETE'
    });
  }

  async validateEmailAccount(
    id: string
  ): Promise<{ success: boolean; message: string }> {
    return this.request(`/api/email/accounts/${id}/validate`, {
      method: 'POST'
    });
  }

  // ============================================
  // Email Templates
  // ============================================

  async listEmailTemplates(): Promise<EmailTemplate[]> {
    return this.request<EmailTemplate[]>('/api/email/templates');
  }

  async getEmailTemplate(id: string): Promise<EmailTemplate> {
    return this.request<EmailTemplate>(`/api/email/templates/${id}`);
  }

  async createEmailTemplate(data: {
    name: string;
    description?: string;
    subject: string;
    body: string;
    format?: 'text' | 'html' | 'both';
    tags?: string[];
  }): Promise<EmailTemplate> {
    return this.request<EmailTemplate>('/api/email/templates', {
      method: 'POST',
      body: JSON.stringify(data)
    });
  }

  async updateEmailTemplate(
    id: string,
    data: Partial<EmailTemplate>
  ): Promise<EmailTemplate> {
    return this.request<EmailTemplate>(`/api/email/templates/${id}`, {
      method: 'PATCH',
      body: JSON.stringify(data)
    });
  }

  async deleteEmailTemplate(id: string): Promise<void> {
    await this.request(`/api/email/templates/${id}`, {
      method: 'DELETE'
    });
  }

  async previewEmailTemplate(
    id: string,
    data: Record<string, any>
  ): Promise<TemplatePreview> {
    return this.request<TemplatePreview>(
      `/api/email/templates/${id}/preview`,
      {
        method: 'POST',
        body: JSON.stringify({ data })
      }
    );
  }

  // ============================================
  // Usage & Rate Limiting
  // ============================================

  async getUsageStats(): Promise<UsageStats> {
    return this.request<UsageStats>('/api/usage');
  }

  // ============================================
  // Import/Export
  // ============================================

  async exportWorkflow(id: string): Promise<WorkflowExport> {
    return this.request<WorkflowExport>(`/api/workflows/${id}/export`);
  }

  async exportWorkflows(ids: string[]): Promise<WorkflowExport> {
    const query = ids.map(id => `ids=${id}`).join('&');
    return this.request<WorkflowExport>(`/api/workflows/export?${query}`);
  }

  async importWorkflows(data: WorkflowExport): Promise<WorkflowImportResult> {
    return this.request<WorkflowImportResult>('/api/workflows/import', {
      method: 'POST',
      body: JSON.stringify(data)
    });
  }
}

