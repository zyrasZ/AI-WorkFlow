// ============================================
// Core Workflow Types
// ============================================

export interface Workflow {
  id: string;
  user_id: string;
  name: string;
  description: string | null;
  nodes: WorkflowNode[];
  edges: WorkflowEdge[];
  is_active: boolean;
  created_at: string;
  updated_at: string;
}

export interface WorkflowNode {
  id: string;
  type: NodeType;
  config: Record<string, any>;
  position?: { x: number; y: number };
  data?: Record<string, any>;
}

export interface WorkflowEdge {
  id: string;
  source: string;
  target: string;
  sourceHandle?: string;
  targetHandle?: string;
}

export type NodeType =
  // Logic Nodes
  | 'if-else'
  | 'switch'
  | 'loop'
  | 'delay'
  | 'merge'
  | 'set-variable'
  | 'code'
  | 'data-mapper'
  // Action Nodes
  | 'send-email'
  | 'read-email'
  | 'ai-chat'
  | 'ai-classifier'
  | 'email-filter'
  | 'email-template';

